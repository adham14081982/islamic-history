n = 0
for c in part['chapters']:
    if c['id'] in ADD and ADD[c['id']] not in c['p']:
        c['p'].append(ADD[c['id']])
        n += 1

with io.open(path, 'w', encoding='utf-8') as f:
    json.dump(part, f, ensure_ascii=False, indent=2)

tot = len(json.dumps(part, ensure_ascii=False))
print('أُضيفت %d فقرة · %d بايت · صفحات~%d' % (n, tot, round(tot / 2600)))
for c in part['chapters']:
    if c['id'] in ADD:
        print('  %-18s p:%d أقصر %d' % (c['id'], len(c['p']), min(len(x) for x in c['p'])))
